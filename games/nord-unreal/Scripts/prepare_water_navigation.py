"""Write native pond boundaries from the same survey as the rendered water; no asset mutations."""
from pathlib import Path
from plateau_park import park_survey
from prepare_plateau import geography
ROOT=Path(__file__).resolve().parents[1]
ponds,_,_=park_survey(); _,roads=geography()
lines=['#pragma once', '#include "CoreMinimal.h"', '// Generated by Scripts/prepare_water_navigation.py from the rendered pond survey.', 'namespace LaFontaineWater {', 'inline constexpr float SurfaceZ = 7.15f;']
rings=[]
for pond,p in enumerate(ponds):
    for hole,key in [(False,'outer'),(True,'inner')]:
        for index,points in enumerate(p[key]):
            name=f'Pond{pond}{key}{index}'
            assert len(points)>=3
            lines.append(f'inline const FVector2D {name}[] = {{')
            lines += [f'    {{{x:.6f}, {y:.6f}}},' for x,y in points]
            lines.append('};');rings.append(f'    {{MakeArrayView({name}), {pond}, {str(hole).lower()}}},')
lines += ['struct FRing { TConstArrayView<FVector2D> Points; int32 Pond; bool bHole; };', 'inline const FRing Rings[] = {', *rings, '};', 'struct FBridge { FVector2D A, B; float HalfWidth; };', 'inline const FBridge Bridges[] = {']
for road in roads:
    if road['tags'].get('bridge') in (None,'no'):continue
    for a,b in zip(road['points'],road['points'][1:]):
        lines.append(f'    {{{{{a[0]:.6f}, {a[1]:.6f}}}, {{{b[0]:.6f}, {b[1]:.6f}}}, {road["width"]/2:.6f}f}},')
lines += ['};', '}']
(ROOT/'Source/Quebec/LaFontaineWater.h').write_text('\n'.join(lines)+'\n')
print('Native pond boundary rings:',len(rings))
