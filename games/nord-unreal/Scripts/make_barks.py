#!/usr/bin/env python3
"""Generate the mission-giver barks with espeak-ng and write QuebecBarks.h.

The spoken words are the residents' own lines. espeak-ng is the voice, and each
giver gets a different voice, pitch and speed. The game plays the committed
samples, so a player does not need espeak-ng.
"""
import base64
import subprocess
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "Source" / "Quebec" / "QuebecBarks.h"
PCM = ROOT / "Source" / "Quebec" / "QuebecBarkPcm.inc"

# voice, pitch 0-99, words per minute, the resident's line
GIVERS = [
    ("en-gb-x-rp+m2", 28, 138, "My superpower? A hole lot of courage."),
    ("en-gb+m5", 58, 128, "I came for the picnic. I stayed for the existential crumbs."),
    ("en-us+f3", 64, 150, "Stay cheesy, Montreal. The fries are counting on you."),
    ("en-us+m3", 42, 156, "Team cottage! Montreal is our warm-up lap."),
    ("en-us-nyc+m4", 36, 148, "Thirty-three points. One plunger. No refunds."),
    ("en-gb-scotland+m3", 34, 142, "I brought backup. It is mostly plumbing supplies."),
    ("en-us+m1", 52, 150, "White cap, black coffee, questionable plan."),
    ("en-029+m3", 40, 152, "I only swing for the fences. And blocked drains."),
    ("en-us+f4", 72, 158, "This jacket is visible from orbit. You are welcome."),
    ("en-gb+m7", 18, 136, "Heavy metal. Light luggage. Emergency plunger."),
    ("en-us+f2", 60, 146, "The bag has everything. Except a sensible explanation."),
]

RATE = 11025


def speak(voice, pitch, speed, text):
    path = Path("/tmp") / "nord-bark.wav"
    run = subprocess.run(
        ["espeak-ng", "-v", voice, "-p", str(pitch), "-s", str(speed), "-w", str(path), text],
        check=True, capture_output=True, text=True)
    if run.stderr.strip():
        raise SystemExit(run.stderr)
    with wave.open(str(path)) as clip:
        if clip.getnchannels() != 1 or clip.getsampwidth() != 2 or clip.getframerate() != 22050:
            raise SystemExit(f"unexpected wav {clip.getnchannels()} {clip.getframerate()}")
        frames = clip.getnframes()
        raw = clip.readframes(frames)
    samples = list(memoryview(raw).cast("h"))
    folded = [(samples[i] + samples[i + 1]) // 2 for i in range(0, len(samples) - 1, 2)]
    loud = 500
    start = next((i for i, sample in enumerate(folded) if abs(sample) > loud), 0)
    end = next((i for i in range(len(folded) - 1, -1, -1) if abs(folded[i]) > loud), len(folded) - 1)
    pad = 80
    start = max(0, start - pad)
    end = min(len(folded), end + 1 + pad)
    clip_samples = folded[start:end]
    fade = 132
    for i in range(min(fade, len(clip_samples))):
        gain = i / fade
        clip_samples[i] = int(clip_samples[i] * gain)
        clip_samples[-1 - i] = int(clip_samples[-1 - i] * gain)
    peak = max(abs(sample) for sample in clip_samples)
    if peak < 1000 or len(clip_samples) < RATE:
        raise SystemExit(f"quiet or short line: {text}")
    return clip_samples


def main():
    pieces = [speak(*giver) for giver in GIVERS]
    blob = bytearray()
    begins = []
    counts = []
    for piece in pieces:
        begins.append(len(blob) // 2)
        counts.append(len(piece))
        blob += b"".join(int(sample).to_bytes(2, "little", signed=True) for sample in piece)
    encoded = base64.b64encode(blob).decode("ascii")
    wrapped = "\n".join(f'    "{encoded[i:i + 120]}"' for i in range(0, len(encoded), 120))
    PCM.write_text(
        "// Generated by Scripts/make_barks.py. espeak-ng 1.51, 11025 Hz, mono.\n"
        "inline constexpr char PcmBase64[] =\n"
        f"{wrapped};\n"
    )
    lines = ",\n        ".join(f'"{text}"' for *_, text in GIVERS)
    voices = "\n".join(
        f"// {index}: {voice} pitch {pitch} speed {speed}"
        for index, (voice, pitch, speed, _) in enumerate(GIVERS)
    )
    HEADER.write_text(f"""#pragma once

// Original spoken lines for the eleven park residents. The words are their
// dialogue. espeak-ng speaks them. Each giver has a different voice.
// No cooked asset. The samples are committed, so play does not need espeak-ng.
{voices}

#include <cstdint>

namespace QuebecBarks
{{
    inline constexpr int SampleRate = {RATE};
    inline constexpr int LineCount = {len(GIVERS)};
    inline constexpr int Begin[LineCount] = {{{", ".join(str(value) for value in begins)}}};
    inline constexpr int Count[LineCount] = {{{", ".join(str(value) for value in counts)}}};
    inline constexpr int PcmSamples = {sum(counts)};

    inline const char* Line(int Style)
    {{
        static const char* Lines[LineCount] = {{
        {lines}
        }};
        if (Style < 0) Style = 0;
        if (Style >= LineCount) Style = LineCount - 1;
        return Lines[Style];
    }}

    struct FSpan
    {{
        int Begin = 0;
        int Count = 0;
    }};

    inline FSpan Span(int Style)
    {{
        if (Style < 0) Style = 0;
        if (Style >= LineCount) Style = LineCount - 1;
        return {{Begin[Style], Count[Style]}};
    }}

#include "QuebecBarkPcm.inc"

    inline int Decode(std::int16_t* Dest, int Capacity)
    {{
        auto Value = [](char Digit) -> int
        {{
            if (Digit >= 'A' && Digit <= 'Z') return Digit - 'A';
            if (Digit >= 'a' && Digit <= 'z') return Digit - 'a' + 26;
            if (Digit >= '0' && Digit <= '9') return Digit - '0' + 52;
            if (Digit == '+') return 62;
            if (Digit == '/') return 63;
            return -1;
        }};
        int Samples = 0;
        int Bits = 0;
        unsigned int Acc = 0;
        for (const char* Cursor = PcmBase64; *Cursor; ++Cursor)
        {{
            const int Digit = Value(*Cursor);
            if (Digit < 0) continue;
            Acc = (Acc << 6) | static_cast<unsigned int>(Digit);
            Bits += 6;
            if (Bits < 8) continue;
            Bits -= 8;
            const unsigned int Byte = (Acc >> Bits) & 0xffu;
            if ((Samples & 1) == 0)
            {{
                if (Samples / 2 < Capacity) Dest[Samples / 2] = static_cast<std::int16_t>(Byte);
            }}
            else if (Samples / 2 < Capacity)
            {{
                const unsigned int Word = static_cast<unsigned int>(static_cast<std::uint16_t>(Dest[Samples / 2])) | (Byte << 8);
                Dest[Samples / 2] = static_cast<std::int16_t>(Word);
            }}
            ++Samples;
        }}
        return Samples / 2;
    }}
}}
""")
    print(f"wrote {sum(counts)} samples, {PCM.stat().st_size} pcm bytes, {HEADER.stat().st_size} header bytes")


if __name__ == "__main__":
    main()
