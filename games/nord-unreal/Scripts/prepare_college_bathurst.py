"""Build the College and Bathurst district start from OSM (ODbL 1.0) and Toronto 3D Massing (OGL - Toronto)."""
import json
import math
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

from shapely.geometry import LineString, Point, Polygon, box as rectangle
from shapely.geometry.polygon import orient
from shapely.ops import unary_union
from shapely.strtree import STRtree

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'Scripts'))
from prepare_lafontaine import ROAD_HIGHWAYS, clip_segment, nearest, road_segments_text, road_widths_text, road_width_cm, tags

DATA = ROOT/'Data/CollegeBathurst'
HEADER = ROOT/'Source/Quebec/CollegeBathurstMap.h'
ORIGIN = (43.6564664, -79.4077041)  # College x Bathurst traffic signal, OSM node 29690663.
BOUNDS = (43.6530, -79.4135, 43.6595, -79.4015)
PATH_HIGHWAYS = ('footway', 'path', 'cycleway', 'pedestrian', 'steps')
SNEAKY_DEES, INTERSECTION = '678313322', '29690663'
ATTRIBUTION = ['© OpenStreetMap contributors, ODbL 1.0',
               'Contains information licensed under the Open Government Licence – Toronto']
LAMP_Z, SPAWN_Z, CAR_Z = 470, 120, 115
GAUGE = 149.5  # TTC broad gauge, 1,495 mm.


def xy(lat, lon):
    return ((lon - ORIGIN[1]) * 111320 * math.cos(math.radians(ORIGIN[0])) * 100,
            (lat - ORIGIN[0]) * 111320 * 100)


def inside(p):
    return BOUNDS[0] <= p[0] <= BOUNDS[2] and BOUNDS[1] <= p[1] <= BOUNDS[3]


def box():
    """Gameplay bounds in centimetres: min x, min y, max x, max y."""
    return (*xy(BOUNDS[0], BOUNDS[1]), *xy(BOUNDS[2], BOUNDS[3]))


def clip_line(points, bounds):
    """Clip a polyline to the bounds; vertices already inside keep their exact source position."""
    unique = [points[0]]
    for p in points[1:]:
        if math.dist(p, unique[-1]) >= 1: unique.append(p)
    lines = []
    within = lambda p: bounds[0] <= p[0] <= bounds[2] and bounds[1] <= p[1] <= bounds[3]
    for a, b in zip(unique, unique[1:]):
        segment = [a, b] if within(a) and within(b) else clip_segment(a, b, bounds)
        if not segment: continue
        if lines and math.dist(lines[-1][-1], segment[0]) < .01: lines[-1].append(segment[1])
        else: lines.append(list(segment))
    return [[[round(x, 3), round(y, 3)] for x, y in line] for line in lines]


def ring(shape):
    """Counter-clockwise exterior ring of the largest part, without the closing point."""
    if shape.geom_type != 'Polygon':
        shape = max(getattr(shape, 'geoms', []), key=lambda g: g.area if g.geom_type == 'Polygon' else 0, default=None)
    if shape is None or shape.geom_type != 'Polygon' or shape.is_empty: return None
    points = list(orient(shape, 1.0).exterior.coords)[:-1]
    return [[round(x, 3), round(y, 3)] for x, y in points]


def compact_json(data):
    """One top-level key per line and one list item per line keeps the generated layout diffable."""
    rows = []
    for key, value in data.items():
        text = json.dumps(value, ensure_ascii=False, separators=(',', ':'))
        if isinstance(value, list) and len(value) > 8 and isinstance(value[0], (list, dict)):
            text = '[\n' + ',\n'.join(json.dumps(v, ensure_ascii=False, separators=(',', ':')) for v in value) + '\n]'
        rows.append(json.dumps(key) + ': ' + text)
    return '{\n' + ',\n'.join(rows) + '\n}\n'


def write_obj(path, name, faces):
    """Same OBJ conventions as prepare_lafontaine.main: y flipped, reversed winding, uv per 3 m."""
    with path.open('w') as f:
        f.write('o ' + name + '\n'); index = 1
        for poly in faces:
            for x, y, z in poly: f.write(f'v {x:.3f} {-y:.3f} {z:.3f}\n')
            horizontal = max(p[2] for p in poly) - min(p[2] for p in poly) < 1
            edge = (poly[1][0] - poly[0][0], poly[1][1] - poly[0][1]); length = math.hypot(*edge) or 1
            for x, y, z in poly:
                uv = (x/300, y/300) if horizontal else ((x*edge[0] + y*edge[1])/length/300, z/300)
                f.write(f'vt {uv[0]:.5f} {uv[1]:.5f}\n')
            f.write('f ' + ' '.join(f'{index+i}/{index+i}' for i in reversed(range(len(poly)))) + '\n'); index += len(poly)


def header_text(data):
    vec = lambda p: 'FVector(' + ','.join(f'{v:.3f}' for v in p) + ')'
    text = ('// Generated by Scripts/prepare_college_bathurst.py from Data/CollegeBathurst.\n'
            '// ' + ATTRIBUTION[0] + '.\n// ' + ATTRIBUTION[1] + '.\n'
            '#pragma once\nnamespace CollegeBathurst {\n')
    text += 'const FVector Spawn=' + vec(data['spawn']) + ';\nconst FVector CarSpawn=' + vec(data['car']) + ';\n'
    text += 'const FVector SneakyDees=' + vec([*data['landmarks']['sneaky_dees']['centroid'], 0]) + ';\n'
    text += road_segments_text(data['roads']) + road_widths_text(data['roads'], data['road_widths'])
    text += 'const FVector StreetLamps[] = {\n' + ',\n'.join(vec(p) for p in data['lamps']) + '\n};\n}\n'
    return text


def main():
    root = ET.parse(DATA/'osm.xml').getroot()
    nodes = {e.get('id'): (float(e.get('lat')), float(e.get('lon'))) for e in root.findall('node')}
    node_tags = {e.get('id'): tags(e) for e in root.findall('node') if e.find('tag') is not None}
    bounds = box(); frame = rectangle(*bounds)
    groups = {}
    def face(mat, points):
        if len(points) >= 3: groups.setdefault(mat, []).append(points)
    def polygon(mat, points, z):
        p = list(points)
        if len(p) > 1 and p[0] == p[-1]: p.pop()
        if sum(a[0]*b[1] - b[0]*a[1] for a, b in zip(p, p[1:] + p[:1])) < 0: p.reverse()
        face(mat, [(x, y, z) for x, y in p])
    def strip(mat, a, b, width, z, offset=0):
        dx, dy = b[0] - a[0], b[1] - a[1]; length = math.hypot(dx, dy)
        if length < 1: return
        ox, oy = -dy/length*offset, dx/length*offset
        a, b = (a[0] + ox, a[1] + oy), (b[0] + ox, b[1] + oy)
        nx, ny = -dy/length*width/2, dx/length*width/2
        polygon(mat, [(a[0]+nx, a[1]+ny), (a[0]-nx, a[1]-ny), (b[0]-nx, b[1]-ny), (b[0]+nx, b[1]+ny)], z)
    def points(e): return [xy(*nodes[n.get('ref')]) for n in e.findall('nd') if n.get('ref') in nodes]

    routes = {}
    for r in root.findall('relation'):
        t = tags(r)
        if t.get('type') == 'route' and t.get('route') == 'tram' and t.get('ref'):
            for m in r.findall('member'):
                if m.get('type') == 'way': routes.setdefault(m.get('ref'), set()).add(t['ref'])
    roads, widths, oneway, names, road_ways = [], [], [], [], []
    paths, path_kinds, trams = [], [], []
    osm_buildings, greens, places = [], [], []
    for e in root.findall('way'):
        t = tags(e); p = points(e); ident = e.get('id')
        if len(p) < 2: continue
        h = t.get('highway')
        if h in ROAD_HIGHWAYS or h in PATH_HIGHWAYS:
            if h in ROAD_HIGHWAYS and t.get('oneway') == '-1': p = p[::-1]
            for line in clip_line(p, bounds):
                if h in ROAD_HIGHWAYS:
                    roads.append(line); widths.append(road_width_cm(t)); road_ways.append(ident)
                    oneway.append(t.get('oneway') in ('yes', 'true', '1', '-1')); names.append(t.get('name', ''))
                else:
                    paths.append(line); path_kinds.append(t.get('footway') or h)
        if t.get('railway') == 'tram':
            for line in clip_line(p, bounds):
                trams.append({'way': ident, 'routes': sorted(routes.get(ident, ())), 'service': t.get('service', ''), 'points': line})
        closed = len(p) > 3 and e.findall('nd')[0].get('ref') == e.findall('nd')[-1].get('ref')
        if 'building' in t and closed:
            shape = Polygon(p).buffer(0)
            if shape.area > 0 and frame.contains(shape.centroid): osm_buildings.append((ident, t, shape))
        if closed and (t.get('leisure') in ('park', 'garden') or t.get('landuse') == 'grass'):
            green = ring(Polygon(p).buffer(0).intersection(frame))
            if green: greens.append(green)
        if t.get('name') and (t.get('amenity') or t.get('shop')):
            centre = Polygon(p).buffer(0).centroid if closed else LineString(p).interpolate(.5, normalized=True)
            if frame.contains(centre): places.append({'name': t['name'], 'kind': t.get('amenity') or t.get('shop'),
                                                      'category': 'amenity' if t.get('amenity') else 'shop', 'osm': 'way/' + ident,
                                                      'position': [round(centre.x, 3), round(centre.y, 3)]})
    for ident, t in node_tags.items():
        if t.get('name') and (t.get('amenity') or t.get('shop')) and inside(nodes[ident]):
            places.append({'name': t['name'], 'kind': t.get('amenity') or t.get('shop'), 'category': 'amenity' if t.get('amenity') else 'shop',
                           'osm': 'node/' + ident, 'position': [round(v, 3) for v in xy(*nodes[ident])]})
    places.sort(key=lambda p: (p['name'], p['osm']))
    lamps = [[*(round(v, 3) for v in xy(*nodes[i])), LAMP_Z] for i, t in node_tags.items() if t.get('highway') == 'street_lamp' and inside(nodes[i])]
    trees = [[round(v, 3) for v in xy(*nodes[i])] for i, t in node_tags.items() if t.get('natural') == 'tree' and inside(nodes[i])]

    # Heights: massing MAX_HEIGHT where a footprint matches, then OSM height, levels x 3.2 m, three storeys.
    massing = json.loads((DATA/'massing.geojson').read_text())['features']
    shapes = [Polygon([xy(lat, lon) for lon, lat in f['geometry']['coordinates'][0]]).buffer(0) for f in massing]
    tree = STRtree(shapes); buildings = []
    for ident, t, shape in osm_buildings:
        best = None
        for i in tree.query(shape):
            overlap = shape.intersection(shapes[i]).area
            if overlap >= .5*min(shape.area, shapes[i].area) and (best is None or overlap > best[0]): best = (overlap, int(i))
        levels = None
        try: levels = int(float(t['building:levels'].split(';')[0]))
        except (KeyError, ValueError): pass
        source, height, src = 'fallback', 960., None
        if best and massing[best[1]]['properties']['MAX_HEIGHT'] > 0:
            source, height = 'massing', massing[best[1]]['properties']['MAX_HEIGHT']*100
            src = massing[best[1]]['properties']['HEIGHT_SRC']
        else:
            try: source, height = 'osm_height', float(t['height'].split()[0])*100
            except (KeyError, ValueError):
                if levels: source, height = 'osm_levels', float(t['building:levels'].split(';')[0])*320
        footprint = ring(shape.intersection(frame))
        if not footprint: continue
        building = {'id': ident, 'footprint': footprint, 'height': round(max(250., min(10000., height)), 1), 'height_source': source, 'levels': levels}
        if src: building['massing_source'] = src
        if t.get('name'): building['name'] = t['name']
        buildings.append(building)
    # Keep measured massing that OSM does not map: the part outside OSM footprints, unless they cover most of it.
    # Footprints with MAX_HEIGHT 0 carry no lidar or model height and are left out.
    covered = unary_union([Polygon(b['footprint']) for b in buildings])
    massing_only = 0
    for i, (f, shape) in enumerate(zip(massing, shapes)):
        height = f['properties']['MAX_HEIGHT']
        if height <= 0 or not frame.contains(shape.centroid) or shape.intersection(covered).area >= .5*shape.area: continue
        footprint = ring(shape.difference(covered).intersection(frame))
        if not footprint or Polygon(footprint).area < 40000: continue
        buildings.append({'id': f'massing-{i}', 'footprint': footprint, 'height': round(max(250., min(10000., height*100)), 1),
                          'height_source': 'massing', 'levels': None, 'massing_source': f['properties']['HEIGHT_SRC']})
        massing_only += 1

    # Sneaky Dee's faces College on its north side; the spawn is on that sidewalk.
    dees = next(b for b in buildings if b['id'] == SNEAKY_DEES)
    dees_shape = Polygon(dees['footprint'])
    college = [line for line, name in zip(roads, names) if name == 'College Street']
    bathurst = [line for line, name in zip(roads, names) if name == 'Bathurst Street']
    fronts = []
    for a, b in zip(dees['footprint'], dees['footprint'][1:] + dees['footprint'][:1]):
        length = math.dist(a, b)
        if length < 200: continue
        mid = ((a[0] + b[0])/2, (a[1] + b[1])/2); normal = ((b[1] - a[1])/length, -(b[0] - a[0])/length)
        toward = nearest(mid, college)[0]
        if (toward[0] - mid[0])*normal[0] + (toward[1] - mid[1])*normal[1] > 0: fronts.append((math.dist(mid, toward), mid, normal, [a, b]))
    _, entrance, normal, college_face = min(fronts)
    def nearest_road(q): return min(range(len(roads)), key=lambda i: LineString(roads[i]).distance(Point(q)))
    best = None
    for line, kind in zip(paths, path_kinds):
        if kind != 'sidewalk': continue
        for a, b in zip(line, line[1:]):
            q = LineString([a, b]).interpolate(LineString([a, b]).project(Point(entrance)))
            q = (q.x, q.y); d = math.dist(q, entrance)
            if (q[0] - entrance[0])*normal[0] + (q[1] - entrance[1])*normal[1] <= 0 or names[nearest_road(q)] != 'College Street': continue
            if best is None or d < best[0]: best = (d, q)
    assert best and best[0] < 2500, 'No College sidewalk in front of Sneaky Dee\'s'
    spawn = [round(best[1][0], 3), round(best[1][1], 3), SPAWN_Z]
    car, yaw = nearest(spawn[:2], college)
    centroid = dees_shape.centroid
    intersection = [round(v, 3) for v in xy(*nodes[INTERSECTION])]

    # Blockout geometry for the separate greybox map.
    face('Ground', [(bounds[0], bounds[1], 0), (bounds[2], bounds[1], 0), (bounds[2], bounds[3], 0), (bounds[0], bounds[3], 0)])
    for green in greens: polygon('Grass', green, 2)
    for line in paths:
        for a, b in zip(line, line[1:]): strip('Path', a, b, 230, 5)
    for line, width, one in zip(roads, widths, oneway):
        for a, b in zip(line, line[1:]):
            strip('Road', a, b, width, 6)
            if width > 380 and not one:
                length = math.dist(a, b)
                for d in range(0, int(length) - 180, 650):
                    q = lambda v: (a[0] + (b[0] - a[0])*v/length, a[1] + (b[1] - a[1])*v/length)
                    strip('Marking', q(d), q(d + 180), 10, 8)
    for track in trams:
        for a, b in zip(track['points'], track['points'][1:]):
            for side in (-1, 1): strip('Tram', a, b, 12, 7, side*GAUGE/2)
    for building in buildings:
        p, height = building['footprint'], building['height']
        landmark = building['id'] == SNEAKY_DEES
        wall = 'Landmark' if landmark else ('Brick', 'Cream', 'Sage')[int(building['id'].removeprefix('massing-')) % 3]
        polygon('Landmark' if landmark else 'Roof', p, height)
        for a, b in zip(p, p[1:] + p[:1]):
            face(wall, [(a[0], a[1], 0), (b[0], b[1], 0), (b[0], b[1], height), (a[0], a[1], height)])
            dx, dy = b[0] - a[0], b[1] - a[1]; length = math.hypot(dx, dy)
            if length < 250: continue
            nx, ny = dy/length*3, -dx/length*3
            for z in range(180, int(height) - 140, 310):
                for d in range(100, int(length) - 180, 300):
                    q = lambda v: (a[0] + dx*v/length + nx, a[1] + dy*v/length + ny)
                    l, r = q(d), q(d + 130)
                    face('Glass', [(l[0], l[1], z), (r[0], r[1], z), (r[0], r[1], z + 160), (l[0], l[1], z + 160)])

    by_source = {}
    for building in buildings: by_source[building['height_source']] = by_source.get(building['height_source'], 0) + 1
    counts = {'roads': len(roads), 'road_segments': sum(len(r) - 1 for r in roads), 'paths': len(paths),
              'tram_lines': len(trams), 'buildings': len(buildings), 'buildings_by_height_source': dict(sorted(by_source.items())),
              'massing_only': massing_only, 'massing_features': len(massing), 'lamps': len(lamps), 'trees': len(trees), 'places': len(places)}
    data = {'origin': ORIGIN, 'bounds': BOUNDS, 'bounds_cm': [round(v, 3) for v in bounds], 'attribution': ATTRIBUTION,
            'sources': {'osm': 'https://api.openstreetmap.org/api/0.6/map?bbox=-79.4140,43.6528,-79.4010,43.6598',
                        'massing': 'https://open.toronto.ca/dataset/3d-massing/ (3D Massing 2025, WGS84)'},
            'spawn': spawn, 'car': [round(car[0], 3), round(car[1], 3), CAR_Z], 'car_yaw': round(yaw, 3),
            'landmarks': {'sneaky_dees': {'osm': 'way/' + SNEAKY_DEES, 'name': "Sneaky Dee's", 'address': '431 College Street',
                                          'centroid': [round(centroid.x, 3), round(centroid.y, 3)], 'footprint': dees['footprint'],
                                          'area_m2': round(dees_shape.area/10000, 2), 'height': dees['height'],
                                          'height_source': dees['height_source'], 'college_face': college_face,
                                          'entrance': [round(v, 3) for v in entrance]},
                          'intersection': {'osm': 'node/' + INTERSECTION, 'name': 'College Street x Bathurst Street', 'position': intersection},
                          'places': places},
            'street_names': sorted({n for n in names if n}), 'counts': counts,
            'roads': roads, 'road_widths': widths, 'road_oneway': oneway, 'road_names': names, 'road_ways': road_ways,
            'paths': paths, 'path_kinds': path_kinds, 'tram_lines': trams, 'lamps': lamps, 'trees': trees, 'buildings': buildings}
    assert college and bathurst and len(lamps) > 0 and len(buildings) > 500 and dees['height_source'] == 'massing'
    (DATA/'layout.json').write_text(compact_json(data))
    out = DATA/'Geometry'; out.mkdir(exist_ok=True)
    for old in out.glob('*.obj'):
        if old.stem not in groups: old.unlink()
    for mat, faces in sorted(groups.items()): write_obj(out/(mat + '.obj'), mat, faces)
    HEADER.write_text(header_text(data))
    print(json.dumps({**counts, 'spawn': spawn, 'car': data['car'], 'car_yaw': data['car_yaw'],
                      'sneaky_dees_height_m': dees['height']/100, 'sneaky_dees_area_m2': data['landmarks']['sneaky_dees']['area_m2'],
                      'groups': {k: len(v) for k, v in sorted(groups.items())}}, indent=2))


if __name__ == '__main__':
    main()
