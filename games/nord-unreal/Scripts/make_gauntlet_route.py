"""Write Source/Quebec/QuebecGauntletRoute.h, the stops of the NORD mobile gauntlet loop.

The eye positions and targets are the replica capture cameras in Data/Plateau/ReplicaGeometry/Streets/manifest.json.
The stop labels, street names, drive order and eye field of view come from Data/Gauntlet/loop.json. Run this script
again after the manifest cameras move (for example when the mirror fix flips Y). --check writes nothing and exits
with status 1 when the header differs from what this script would write.
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
LOOP = ROOT / 'Data/Gauntlet/loop.json'
MANIFEST = ROOT / 'Data/Plateau/ReplicaGeometry/Streets/manifest.json'
HEADER = ROOT / 'Source/Quebec/QuebecGauntletRoute.h'


def stops(loop, manifest):
    """The stops in drive order as (label, name, camera, eye, target), with eye and target as (x, y, z) in cm."""
    cameras = {camera['name']: camera for camera in manifest['cameras']}
    if len(cameras) != len(manifest['cameras']):
        raise SystemExit('duplicate camera names in the manifest')
    by_label = {stop['label']: stop for stop in loop['stops']}
    if len(by_label) != len(loop['stops']):
        raise SystemExit('duplicate stop labels in loop.json')
    if sorted(loop['order']) != sorted(by_label):
        raise SystemExit('loop.json order must name every stop once')
    rows = []
    for label in loop['order']:
        stop = by_label[label]
        if stop['camera'] not in cameras:
            raise SystemExit(f"camera {stop['camera']} of stop {label} is not in the manifest")
        camera = cameras[stop['camera']]
        eye, target = (tuple(float(v) for v in camera[key]) for key in ('position', 'target'))
        if len(eye) != 3 or len(target) != 3:
            raise SystemExit(f"camera {stop['camera']} needs a 3D position and target")
        text = label + stop['name'] + stop['camera']
        if not text.isascii() or not text.replace('_', '').isalnum():
            raise SystemExit(f'stop {label}: label, name and camera must be ASCII letters, digits or _')
        rows.append((label, stop['name'], stop['camera'], eye, target))
    return rows


def header_text(rows, fov):
    number = lambda v: f'{v:.3f}'
    body = ',\n'.join(f'        {{"{label}", "{name}", "{camera}", ' + ', '.join(number(v) for v in (*eye, *target)) + '}'
                      for label, name, camera, eye, target in rows)
    order = ' > '.join(label for label, *_ in rows) + ' > ' + rows[0][0]
    return ('// Generated by Scripts/make_gauntlet_route.py from Data/Plateau/ReplicaGeometry/Streets/manifest.json (cameras)\n'
            '// and Data/Gauntlet/loop.json (stops, order, eye_fov_deg). Do not edit; run the script again.\n'
            '#pragma once\n'
            '\n'
            '// The NORD mobile gauntlet stops in drive order: ' + order + '.\n'
            '// Eye and Target are the replica capture camera in map centimetres, as in the manifest. No Unreal includes.\n'
            'namespace QuebecGauntletRoute\n'
            '{\n'
            '    struct FStop\n'
            '    {\n'
            '        const char* Label;\n'
            '        const char* Name;\n'
            '        const char* Camera;\n'
            '        double EyeX, EyeY, EyeZ;\n'
            '        double TargetX, TargetY, TargetZ;\n'
            '    };\n'
            '\n'
            f'    inline constexpr double EyeFieldOfView = {float(fov):.1f};\n'
            f'    inline constexpr int StopCount = {len(rows)};\n'
            '    inline constexpr FStop Stops[StopCount] = {\n'
            + body + '\n'
            '    };\n'
            '}\n')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='exit 1 when the header is stale; write nothing')
    parser.add_argument('--loop', type=Path, default=LOOP)
    parser.add_argument('--manifest', type=Path, default=MANIFEST)
    parser.add_argument('--header', type=Path, default=HEADER)
    args = parser.parse_args(argv)
    loop = json.loads(args.loop.read_text())
    rows = stops(loop, json.loads(args.manifest.read_text()))
    text = header_text(rows, loop['eye_fov_deg'])
    if args.check:
        current = args.header.read_text() if args.header.exists() else ''
        if current != text:
            print(f'NORD_GAUNTLET_ROUTE_STALE {args.header}: run Scripts/make_gauntlet_route.py', file=sys.stderr)
            return 1
        print('NORD_GAUNTLET_ROUTE_CURRENT', len(rows), 'stops')
        return 0
    args.header.write_text(text)
    print('NORD_GAUNTLET_ROUTE', len(rows), 'stops:', ', '.join(f'{label} {name}' for label, name, *_ in rows))
    return 0


if __name__ == '__main__':
    sys.exit(main())
