"""Write the La Fontaine street lamp positions for the sky actor from the checked-in OSM snapshot (ODbL)."""
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'Scripts'))
from prepare_lafontaine import DATA, inside, tags, xy

HEADER = ROOT/'Source/Quebec/LaFontaineLamps.h'
# Under the lamp heads and 15 cm below the bottom of the comic park globe (z 455.5-498.5, build_park_comic.py),
# so the unshadowed pool light reaches the globe's outside instead of sitting inside it.
LAMP_Z = 440


def lamps():
    """Every highway=street_lamp node inside the La Fontaine bounds, in OSM id order, in centimetres."""
    root = ET.parse(DATA/'osm.xml').getroot()
    found = []
    for e in root.findall('node'):
        p = (float(e.get('lat')), float(e.get('lon')))
        if tags(e).get('highway') == 'street_lamp' and inside(p): found.append((int(e.get('id')), [*xy(*p), LAMP_Z]))
    return [p for _, p in sorted(found)]


def header_text(points):
    vec = lambda p: 'FVector(' + ','.join(f'{v:.3f}' for v in p) + ')'
    return ('// Generated by Scripts/prepare_lafontaine_lamps.py. OSM contributors, ODbL 1.0.\n#pragma once\nnamespace LaFontaine {\n'
            'const FVector StreetLamps[] = {\n' + ',\n'.join(vec(p) for p in points) + '\n};\n}\n')


def main():
    points = lamps()
    HEADER.write_text(header_text(points))
    print('NORD_LAFONTAINE_LAMPS', len(points), 'lamps')


if __name__ == '__main__':
    main()
