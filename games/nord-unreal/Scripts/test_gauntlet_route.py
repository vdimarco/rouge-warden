"""Check Source/Quebec/QuebecGauntletRoute.h against the replica manifest cameras and Data/Gauntlet/loop.json.

Scripts/make_gauntlet_route.py writes the header. This test reads the header numbers itself and compares them with the
manifest, runs the generator's --check, and shows the mirror-fix rule: after the cameras move, --check fails until the
header is written again. The moved cameras and the rewritten header are temporary copies; the real files never change.
"""
import json
from pathlib import Path
import re
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "Scripts/make_gauntlet_route.py"
HEADER = ROOT / "Source/Quebec/QuebecGauntletRoute.h"
MANIFEST = ROOT / "Data/Plateau/ReplicaGeometry/Streets/manifest.json"
LOOP_FILE = ROOT / "Data/Gauntlet/loop.json"
LOOP = json.loads(LOOP_FILE.read_text())
NUMBER = r"(-?\d+\.\d{3})"
ROW = re.compile(r'\{"(\w+)", "(\w+)", "(\w+)", ' + ", ".join([NUMBER] * 6) + r"\}")


def rows(text):
    """The header's stops as (label, name, camera, eye, target)."""
    return [(label, name, camera, tuple(map(float, numbers[:3])), tuple(map(float, numbers[3:])))
            for label, name, camera, *numbers in ROW.findall(text)]


def generate(*arguments):
    return subprocess.run([sys.executable, str(SCRIPT), *map(str, arguments)], capture_output=True, text=True)


def expected_rows(manifest):
    cameras = {camera["name"]: camera for camera in manifest["cameras"]}
    stops = {stop["label"]: stop for stop in LOOP["stops"]}
    return [(label, stops[label]["name"], stops[label]["camera"], tuple(map(float, cameras[stops[label]["camera"]]["position"])),
             tuple(map(float, cameras[stops[label]["camera"]]["target"]))) for label in LOOP["order"]]


original = HEADER.read_text()
manifest = json.loads(MANIFEST.read_text())

# The header holds the manifest cameras in loop.json drive order, the eye field of view, and no includes.
found = rows(original)
assert found == expected_rows(manifest), f"QuebecGauntletRoute.h differs from the manifest:\n{found}\n{expected_rows(manifest)}"
assert len(found) == len(LOOP["stops"]) == 5, len(found)
assert f"inline constexpr double EyeFieldOfView = {float(LOOP['eye_fov_deg']):.1f};" in original, "eye field of view"
assert f"inline constexpr int StopCount = {len(found)};" in original, "stop count"
assert "#include" not in original and "Generated by Scripts/make_gauntlet_route.py" in original, "a generated header without includes"
assert " > ".join(LOOP["order"] + LOOP["order"][:1]) in original, "the drive order comment"

# --check passes on the real files and writes nothing.
current = generate("--check")
assert current.returncode == 0 and "NORD_GAUNTLET_ROUTE_CURRENT 5 stops" in current.stdout, current.stdout + current.stderr

with tempfile.TemporaryDirectory() as directory:
    folder = Path(directory)
    # The mirror fix flips Y. A stale header fails --check and is not rewritten.
    flipped = json.loads(MANIFEST.read_text())
    for camera in flipped["cameras"]:
        camera["position"][1] = -camera["position"][1]
        camera["target"][1] = -camera["target"][1]
    moved = folder / "manifest.json"
    moved.write_text(json.dumps(flipped))
    stale = generate("--check", "--manifest", moved)
    assert stale.returncode == 1 and "NORD_GAUNTLET_ROUTE_STALE" in stale.stderr, stale.stdout + stale.stderr
    assert HEADER.read_text() == original, "--check must not write the header"

    # Running the generator again makes it current: the copy then holds the flipped cameras.
    copy = folder / "QuebecGauntletRoute.h"
    copy.write_text(original)
    written = generate("--manifest", moved, "--header", copy)
    assert written.returncode == 0 and "NORD_GAUNTLET_ROUTE 5 stops" in written.stdout, written.stdout + written.stderr
    again = generate("--check", "--manifest", moved, "--header", copy)
    assert again.returncode == 0, again.stdout + again.stderr
    assert rows(copy.read_text()) == expected_rows(flipped), "the rewritten header holds the flipped cameras"
    assert all(eye[1] == -before[3][1] for (*_, eye, _target), before in zip(rows(copy.read_text()), found)), "Y flipped"

    # A missing header and a changed drive order are stale too.
    missing = generate("--check", "--header", folder / "absent.h")
    assert missing.returncode == 1 and "NORD_GAUNTLET_ROUTE_STALE" in missing.stderr, missing.stdout + missing.stderr
    reordered = json.loads(LOOP_FILE.read_text())
    reordered["order"] = reordered["order"][::-1]
    loop_copy = folder / "loop.json"
    loop_copy.write_text(json.dumps(reordered))
    order = generate("--check", "--loop", loop_copy)
    assert order.returncode == 1 and "NORD_GAUNTLET_ROUTE_STALE" in order.stderr, order.stdout + order.stderr

    # A stop whose camera is gone stops the generator with a message and leaves the header alone.
    pruned = json.loads(MANIFEST.read_text())
    pruned["cameras"] = [camera for camera in pruned["cameras"] if camera["name"] != LOOP["stops"][0]["camera"]]
    gone = folder / "pruned.json"
    gone.write_text(json.dumps(pruned))
    before = copy.read_text()
    broken = generate("--manifest", gone, "--header", copy)
    assert broken.returncode != 0 and LOOP["stops"][0]["camera"] in broken.stderr and copy.read_text() == before, broken.stdout + broken.stderr

assert HEADER.read_text() == original, "the real header never changes"
print("NORD_GAUNTLET_ROUTE_OK", len(found), "stops:", ", ".join(f"{label} {name} eye ({eye[0]:.0f}, {eye[1]:.0f})" for label, name, _, eye, _ in found))
