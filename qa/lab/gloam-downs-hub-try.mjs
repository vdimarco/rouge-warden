// scratch: look at the hall in a browser
import fs from 'node:fs';
import { createRequire } from 'node:module';
const { chromium } = createRequire(new URL('../browser/x.mjs', import.meta.url))('playwright');
const SITE = (process.env.SITE_URL || 'http://127.0.0.1:8951').replace(/\/$/, '');
const OUT = process.env.SHOTS || '/tmp/hubtry';
fs.mkdirSync(OUT, { recursive: true });
const GL = ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'];
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: GL });
const [w, h] = (process.env.SIZE || '1280x720').split('x').map(Number);
const ctx = await browser.newContext({ viewport: { width: w, height: h }, ...(process.env.TOUCH ? { hasTouch: true, isMobile: true } : {}) });
const page = await ctx.newPage();
page.on('pageerror', e => console.log('ERR', e.message));
page.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') console.log('CONSOLE', m.text()); });
await page.goto(`${SITE}/lab/gloam-downs/?run&test&fresh`);
await page.waitForFunction(() => window.__gloam?.ready(), null, { timeout: 180000 });
const G = (fn, a) => page.evaluate(fn, a);
await G(() => { window.__gloam.close?.(); });
await G(() => { document.querySelectorAll('.panel:not([hidden])').forEach(p => (p.hidden = true)); });
await G(() => window.__gloam.go('lamproom'));
await page.waitForFunction(() => window.__gloam.ready() && window.__gloam.state().place === 'lamproom', null, { timeout: 180000 });
console.log(JSON.stringify(await G(() => ({ s: window.__gloam.state().mode, hall: window.__gloam.hall() }))).slice(0, 600));
await G(() => window.__gloam.tick(3.5, {}, true));
await page.screenshot({ path: `${OUT}/start.png` });
const script = process.env.STEPS || 'kiln';
for (const id of script.split(',')) {
  const st = await G(i => window.__gloam.hall().stations.find(s => s.id === i), id);
  const yaw = Math.atan2(st.obj[0] - st.at[0], st.obj[1] - st.at[1]);
  await G(([x, z, y]) => window.__gloam.teleport(x, z, y), [st.at[0], st.at[1], yaw]);
  await G(() => window.__gloam.tick(1.2, {}, true));
  console.log(id, JSON.stringify(await G(() => window.__gloam.hall().near)), JSON.stringify(await G(() => window.__gloam.hall().prompt)));
  await page.screenshot({ path: `${OUT}/${id}-prompt.png` });
  await G(() => window.__gloam.use());
  await G(() => window.__gloam.draw());
  console.log(JSON.stringify(await G(() => ({ mode: window.__gloam.run().mode, h: window.__gloam.hall().station, layout: window.__gloam.hall().layout }))));
  await page.screenshot({ path: `${OUT}/${id}-card.png` });
  await page.keyboard.press('Escape');
  await G(() => window.__gloam.tick(0.1, {}, true));
}
await browser.close();
