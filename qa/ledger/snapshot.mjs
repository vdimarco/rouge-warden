// Rebuilds public/ledger/prices.js from the live 1Click API: token prices, and each payout asset's
// fee (a fixed part in USD and a share of the amount), fitted from two dry EXACT_OUTPUT quotes.
// Run: node qa/ledger/snapshot.mjs
import fs from "node:fs";
import { ASSETS, ONECLICK, quotePay, fromUnits } from "../../public/ledger/intents.js";

const tokens = await (await fetch(ONECLICK + "/v0/tokens")).json();
const price = (id) => tokens.find((t) => t.assetId === id)?.price;
const nearUsd = price(ASSETS.wnear.id);
const out = { at: new Date().toISOString(), nearUsd, assets: {} };
for (const [key, a] of Object.entries(ASSETS)) {
  const usd = price(a.id);
  if (!usd) throw new Error("no price for " + key);
  const pts = [];
  for (const amt of [1.5, 6]) {
    const q = await quotePay({ asset: key, amount: amt, recipient: a.sample });
    pts.push({ usdOut: amt * usd, usdIn: q.nearIn * nearUsd });
  }
  // usdIn = usdOut * (1 + pct) + fixed
  const pct = (pts[1].usdIn - pts[0].usdIn) / (pts[1].usdOut - pts[0].usdOut) - 1;
  const fixed = pts[0].usdIn - pts[0].usdOut * (1 + pct);
  out.assets[key] = { usd, pct: +pct.toFixed(5), fixed: +Math.max(0, fixed).toFixed(4) };
  console.log(key, out.assets[key]);
}
const body = "// Generated by qa/ledger/snapshot.mjs from the 1Click API. Offline prices and fees for Warden's Ledger.\nexport const SNAPSHOT = " + JSON.stringify(out, null, 2) + ";\n";
fs.writeFileSync(new URL("../../public/ledger/prices.js", import.meta.url), body);
console.log("wrote public/ledger/prices.js");
